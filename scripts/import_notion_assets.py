def month_end(date_str):
    """將 YYYY-MM-DD 轉成該月最後一天的 YYYY-MM-DD。"""
    y, m = int(date_str[:4]), int(date_str[5:7])
    last = calendar.monthrange(y, m)[1]
    return f'{y:04d}-{m:02d}-{last:02d}'


