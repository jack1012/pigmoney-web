def build_rows():
    """將 RAW_DATA 展開成 (date, ano, amount) 列表，date 轉月底。
    同月份若有多筆，保留 notion_date 較晚（字母序較大）的那筆。
    """
    # key=(month_end_date, ano)，value=(notion_date, amount)
    best = {}
    for notion_date, fields in RAW_DATA:
        date_str = month_end(notion_date)
        for field, amount in fields.items():
            ano = FIELD_TO_ANO.get(field)
            if ano is None:
                continue
            key = (date_str, ano)
            if key not in best or notion_date > best[key][0]:
                best[key] = (notion_date, amount)

    rows = [(date_str, ano, v[1]) for (date_str, ano), v in best.items()]
    rows.sort()
    return rows


def main():
    rows = build_rows()

    conn = sqlite3.connect(DB_PATH)
    conn.text_factory = bytes  # 避免編碼問題

    cur = conn.cursor()
    inserted = 0
    for date_str, ano, amount in rows:
        cur.execute(
            'INSERT OR REPLACE INTO asset_snapshot (date, ano, amount) VALUES (?, ?, ?)',
            (date_str, ano, amount)
        )
        inserted += 1

    conn.commit()
    conn.close()

    print(f'完成。共處理 {len(RAW_DATA)} 個月份頁面，寫入 {inserted} 筆記錄。')

    # 統計各月份
    from collections import defaultdict
    by_month = defaultdict(list)
    for date_str, ano, amount in rows:
        by_month[date_str].append(ano)
    print(f'涵蓋月份（共 {len(by_month)} 個）：')
    for d in sorted(by_month.keys()):
        print(f'  {d}  ({len(by_month[d])} 個帳戶)')


if __name__ == '__main__':
    main()
